-- Initial database schema for Roster
-- Multi-tenant ready with team_id in all tables

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Team table - tenancy root
CREATE TABLE IF NOT EXISTS team (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- User table - team members
CREATE TABLE IF NOT EXISTS "user" (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    team_id UUID NOT NULL REFERENCES team(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    avatar_url TEXT,
    role VARCHAR(20) NOT NULL CHECK (role IN ('manager', 'member')),
    auth_provider VARCHAR(20) NOT NULL CHECK (auth_provider IN ('google', 'facebook')),
    provider_subject VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    UNIQUE(auth_provider, provider_subject)
);

-- Shift type definitions
CREATE TABLE IF NOT EXISTS shift_type (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    team_id UUID NOT NULL REFERENCES team(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    color VARCHAR(50) NOT NULL,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Schedule period (weekly/monthly)
CREATE TABLE IF NOT EXISTS schedule_period (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    team_id UUID NOT NULL REFERENCES team(id) ON DELETE CASCADE,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('draft', 'collecting_wishes', 'solving', 'proposed', 'published')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Day shift slots - shifts assigned to specific dates
CREATE TABLE IF NOT EXISTS day_shift_slot (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    period_id UUID NOT NULL REFERENCES schedule_period(id) ON DELETE CASCADE,
    date DATE NOT NULL,
    shift_type_id UUID NOT NULL REFERENCES shift_type(id),
    min_staff INTEGER NOT NULL DEFAULT 1,
    max_staff INTEGER NOT NULL DEFAULT 1,
    UNIQUE(period_id, date, shift_type_id)
);

-- Member constraints (vacations, preferences, etc.)
CREATE TABLE IF NOT EXISTS member_constraint (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    period_id UUID NOT NULL REFERENCES schedule_period(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('vacation', 'unavailable', 'preference_avoid', 'preference_want')),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    shift_type_id UUID REFERENCES shift_type(id) ON DELETE SET NULL,
    note TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Roster proposals generated by solver
CREATE TABLE IF NOT EXISTS roster_proposal (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    period_id UUID NOT NULL REFERENCES schedule_period(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    soft_penalty_total INTEGER NOT NULL DEFAULT 0,
    hard_violation_count INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL CHECK (status IN ('candidate', 'selected'))
);

-- Individual assignments in a proposal
CREATE TABLE IF NOT EXISTS assignment (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    proposal_id UUID NOT NULL REFERENCES roster_proposal(id) ON DELETE CASCADE,
    date DATE NOT NULL,
    shift_type_id UUID NOT NULL REFERENCES shift_type(id),
    user_id UUID NOT NULL REFERENCES "user"(id),
    UNIQUE(proposal_id, date, shift_type_id, user_id)
);

-- Constraint violations for proposals
CREATE TABLE IF NOT EXISTS violation (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    proposal_id UUID NOT NULL REFERENCES roster_proposal(id) ON DELETE CASCADE,
    constraint_kind VARCHAR(50) NOT NULL,
    hard BOOLEAN NOT NULL,
    user_id UUID REFERENCES "user"(id) ON DELETE SET NULL,
    date DATE,
    message TEXT NOT NULL,
    penalty INTEGER NOT NULL DEFAULT 0
);

-- Create indexes for performance
CREATE INDEX IF NOT EXISTS idx_user_team ON "user"(team_id);
CREATE INDEX IF NOT EXISTS idx_user_email ON "user"(email);
CREATE INDEX IF NOT EXISTS idx_shift_type_team ON shift_type(team_id);
CREATE INDEX IF NOT EXISTS idx_schedule_period_team ON schedule_period(team_id);
CREATE INDEX IF NOT EXISTS idx_schedule_period_status ON schedule_period(status);
CREATE INDEX IF NOT EXISTS idx_day_shift_slot_period ON day_shift_slot(period_id);
CREATE INDEX IF NOT EXISTS idx_day_shift_slot_date ON day_shift_slot(date);
CREATE INDEX IF NOT EXISTS idx_member_constraint_period ON member_constraint(period_id);
CREATE INDEX IF NOT EXISTS idx_member_constraint_user ON member_constraint(user_id);
CREATE INDEX IF NOT EXISTS idx_roster_proposal_period ON roster_proposal(period_id);
CREATE INDEX IF NOT EXISTS idx_assignment_proposal ON assignment(proposal_id);
CREATE INDEX IF NOT EXISTS idx_assignment_user ON assignment(user_id);
CREATE INDEX IF NOT EXISTS idx_assignment_date ON assignment(date);
CREATE INDEX IF NOT EXISTS idx_violation_proposal ON violation(proposal_id);

